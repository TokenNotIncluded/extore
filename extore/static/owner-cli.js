"use strict";

(() => {
  const mounts = new WeakMap();
  const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
  const esc = (value) => String(value ?? "").replace(/[&<>"']/g, (char) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[char]);
  const codeValue = (value) => String(value ?? "").trim().toUpperCase().replaceAll("-", "");
  const validCode = (value) => /^[ABCDEFGHJKLMNPQRSTUVWXYZ23456789]{12}$/.test(codeValue(value));
  const decode = (value) => {
    if (typeof value !== "string" || !/^[A-Za-z0-9_-]{1,4096}$/.test(value)) throw new Error("Invalid Passkey options");
    return Uint8Array.from(atob(value.replaceAll("-", "+").replaceAll("_", "/")), (char) => char.charCodeAt(0));
  };
  const encode = (value) => btoa(String.fromCharCode(...new Uint8Array(value)))
    .replaceAll("+", "-").replaceAll("/", "_").replace(/=+$/, "");

  function mount({ root, requestId, api, language } = {}) {
    if (!root?.querySelector || typeof api !== "function") throw new TypeError("Owner CLI approval requires a root element and API function");
    mounts.get(root)?.dispose();
    let disposed = false;
    let pending = null;
    let details = null;
    let deviceCode = "";
    let approvalToken = "";
    let approvalMode = "passkey";
    let state = "code";
    let revision = 0;
    const id = typeof requestId === "string" ? requestId : "";
    const active = () => !disposed && root.isConnected !== false;
    const lang = () => {
      const preferred = typeof language === "function" ? language() : language;
      return String(preferred || window.ExtorePreferences?.resolved?.language || window.navigator?.language || "zh-CN").toLowerCase().startsWith("en") ? "en" : "zh-CN";
    };
    const tr = (cn, en) => lang() === "en" ? en : cn;
    const date = (seconds) => new Date(seconds * 1000).toLocaleString(lang() === "en" ? "en-GB" : "zh-CN");
    const page = (body) => {
      if (active()) root.innerHTML = `<div class="narrow"><h1>${tr("授权商家 CLI 设备", "Authorize merchant CLI device")}</h1>${body}</div>`;
    };
    const errorText = (error) => {
      if (error?.name === "NotAllowedError" || error?.name === "AbortError")
        return tr("Passkey 验证已取消或超时，设备尚未获得授权。确认 CLI 仍在等待后可以重试。", "Passkey verification was cancelled or timed out. The device has not been authorized. You can retry while the CLI request is still pending.");
      return typeof error?.message === "string" && error.message.length <= 1000
        ? error.message
        : tr("授权未完成，请检查 CLI 请求后重试。", "Authorization was not completed. Check the CLI request and retry.");
    };
    const bind = (selector, event, handler) => root.querySelector(selector)?.addEventListener(event, handler);
    const clear = () => { details = null; deviceCode = ""; approvalToken = ""; approvalMode = "passkey"; };
    function failed(error) {
      const message = errorText(error);
      details = null;
      approvalToken = "";
      codePage(message);
      if (/过期|失效|expired/i.test(message)) state = "expired";
      else if (/拒绝|撤销|denied|revoked/i.test(message)) state = "denied";
      else if (error?.name === "NotAllowedError" || error?.name === "AbortError") state = "cancelled";
      else state = "error";
    }

    function codePage(message = "") {
      state = uuid.test(id) ? "code" : "invalid";
      if (state === "invalid") {
        page(`<p class="error" role="alert">${tr("授权请求 ID 无效，请使用 CLI 刚生成的完整授权网址。", "Invalid authorization request ID. Open the complete authorization URL generated by the CLI.")}</p><a href="/">${tr("返回首页", "Return home")}</a>`);
        return;
      }
      page(`<p>${tr("在 CLI 中核对正在等待授权的设备，再输入它显示的设备码。", "Check the device waiting for authorization in your CLI, then enter the device code it displays.")}</p><section class="panel"><form id="owner-cli-code-form"><div class="field"><label for="owner-cli-code">${tr("CLI 设备码", "CLI device code")}</label><input id="owner-cli-code" type="password" class="code" autocomplete="off" autocapitalize="characters" spellcheck="false" maxlength="64" required placeholder="XXXX-XXXX-XXXX" value="${esc(deviceCode)}"></div><div class="actions"><button id="owner-cli-review" type="submit">${tr("核对设备与权限", "Review device and permissions")}</button><button id="owner-cli-password" class="secondary" type="button">${tr("使用店铺邮箱与密码", "Use shop email and password")}</button></div></form><p id="owner-cli-error" class="error" role="alert">${esc(message)}</p></section><p class="caption">${tr("核对设备不会授权。确认具体店铺或平台管理员范围后，使用新的 Passkey 验证或店铺密码批准；已启用二次验证的店铺还需动态码或恢复码。已登录浏览器不能直接批准设备。", "Reviewing does not authorize the device. Confirm the specific shop or platform administrator scope, then approve with a fresh Passkey verification or shop password. Shops with second verification enabled also require an authenticator or recovery code. An existing browser login cannot approve the device by itself.")}</p>`);
      const readCode = () => {
        const input = root.querySelector("#owner-cli-code");
        deviceCode = String(input?.value || "").trim().toUpperCase();
        if (validCode(deviceCode)) return true;
        const error = root.querySelector("#owner-cli-error");
        if (error) error.textContent = tr("请输入 CLI 显示的 12 位设备码，例如 XXXX-XXXX-XXXX。", "Enter the 12-character device code displayed by the CLI, such as XXXX-XXXX-XXXX.");
        input?.focus();
        return false;
      };
      bind("#owner-cli-password", "click", () => {
        if (!active() || pending || !readCode()) return;
        details = null;
        approvalToken = "";
        passwordPage();
      });
      bind("#owner-cli-code-form", "submit", async (event) => {
        event.preventDefault();
        if (!active() || pending) return;
        if (!readCode()) return;
        const button = root.querySelector("#owner-cli-review");
        if (button) button.disabled = true;
        const controller = new AbortController();
        pending = controller;
        const version = ++revision;
        try {
          const response = await api("/auth/cli-owner/options", { request_id: id, device_code: deviceCode }, "POST", { signal: controller.signal });
          if (!active() || version !== revision) return;
          validate(response);
          details = response;
          approvalMode = "passkey";
          approvalToken = "";
          detailsPage();
        } catch (error) {
          if (active() && version === revision) failed(error);
        } finally {
          if (pending === controller) pending = null;
          if (active() && version === revision && button?.isConnected !== false) button.disabled = false;
        }
      });
    }

    function validate(value, password = false) {
      const options = value?.options;
      const methods = value?.approval_methods;
      const hostname = new URL(window.location.origin).hostname;
      if (!value || typeof value.request_id !== "string" || value.request_id.toLowerCase() !== id.toLowerCase()
        || value.role !== "admin" || value.scope !== "shop.owner"
        || typeof value.superadmin !== "boolean"
        || (value.superadmin ? value.shop_id !== null : typeof value.shop_id !== "string" || !uuid.test(value.shop_id))
        || typeof value.shop_name !== "string" || !value.shop_name.trim() || value.shop_name.length > 200
        || typeof value.mfa_required !== "boolean" || (value.superadmin && value.mfa_required)
        || !Array.isArray(methods) || methods.length < 1 || methods.length > 2
        || methods.some((method) => !["passkey", "password", "password_totp"].includes(method))
        || new Set(methods).size !== methods.length
        || (value.superadmin && methods.some((method) => method !== "passkey"))
        || methods.includes(value.mfa_required ? "password" : "password_totp")
        || !validCode(value.device_code)
        || codeValue(value.device_code) !== codeValue(deviceCode)
        || typeof value.client_name !== "string" || !value.client_name.trim() || value.client_name.length > 200
        || !/^[0-9a-f]{64}$/.test(value.fingerprint || "")
        || !Number.isFinite(value.expires) || value.expires * 1000 <= Date.now()
        || value.expires * 1000 > Date.now() + 630 * 1000
        || !Number.isFinite(value.grant_expires) || value.grant_expires * 1000 <= Date.now()
        || value.grant_expires * 1000 > Date.now() + (30 * 86400 + 300) * 1000)
        throw new Error(tr("设备授权信息无效或已过期，请从 CLI 重新申请。", "Device authorization details are invalid or expired. Create a new request in the CLI."));
      if (password) {
        if (value.superadmin || value.options !== null || methods.length !== 1
          || methods[0] !== (value.mfa_required ? "password_totp" : "password")
          || typeof value.approval_token !== "string" || !/^[A-Za-z0-9_-]{43}$/.test(value.approval_token)
          || !Number.isFinite(value.approval_expires) || value.approval_expires * 1000 <= Date.now()
          || value.approval_expires * 1000 > Date.now() + 305 * 1000 || value.approval_expires > value.expires)
          throw new Error(tr("店铺设备验证信息无效，请重新核对。", "Invalid shop device verification details. Review the device again."));
        return;
      }
      if (options === null && methods.length === 1 && methods[0] === (value.mfa_required ? "password_totp" : "password") && !value.superadmin) return;
      if (!methods.includes("passkey") || !options || options.userVerification !== "required" || options.rpId !== hostname
        || (options.allowCredentials !== undefined && (!Array.isArray(options.allowCredentials) || options.allowCredentials.length > 128)))
        throw new Error(tr("设备授权信息无效或已过期，请从 CLI 重新申请。", "Device authorization details are invalid or expired. Create a new request in the CLI."));
      decode(options.challenge);
      options.allowCredentials?.forEach((credential) => {
        if (credential?.type !== "public-key") throw new Error(tr("Passkey 验证信息无效。", "Invalid Passkey verification options."));
        decode(credential.id);
      });
    }

    function passwordPage() {
      if (!active()) return;
      if (window.isSecureContext === false) {
        codePage(tr("请在 HTTPS 安全页面中验证店铺账号。", "Verify the shop account on a secure HTTPS page."));
        return;
      }
      state = "password";
      page(`<p>${tr("输入店铺账号和新的验证信息。验证通过后还需核对具体店铺与设备，再单独批准；此步不会授权。", "Enter your shop account and fresh verification factors. After verification, review the specific shop and device before approving separately. This step does not authorize the device.")}</p><section class="panel"><form id="owner-cli-password-form"><div class="field"><label for="owner-cli-email">${tr("店铺账号邮箱", "Shop account email")}</label><input id="owner-cli-email" type="email" autocomplete="username" maxlength="254" required></div><div class="field"><label for="owner-cli-account-password">${tr("店铺密码", "Shop password")}</label><input id="owner-cli-account-password" type="password" autocomplete="current-password" maxlength="200" required></div><div class="field"><label for="owner-cli-factor-method">${tr("二次验证方式", "Second verification method")}</label><select id="owner-cli-factor-method"><option value="code">${tr("验证器动态码", "Authenticator code")}</option><option value="backup_code">${tr("恢复码", "Recovery code")}</option></select></div><div class="field"><label id="owner-cli-factor-label" for="owner-cli-factor">${tr("验证器动态码", "Authenticator code")}</label><input id="owner-cli-factor" type="password" autocomplete="off" spellcheck="false" maxlength="100"><p class="caption">${tr("已启用二次验证的账号必须填写；未启用的账号可留空。", "Required for accounts with second verification enabled; otherwise leave blank.")}</p></div><div class="actions"><button id="owner-cli-password-review" type="submit">${tr("验证账号并核对权限", "Verify account and review permissions")}</button><button id="owner-cli-password-back" class="secondary" type="button">${tr("返回设备码", "Back to device code")}</button></div></form><p id="owner-cli-error" class="error" role="alert"></p><p class="caption">${tr("平台管理员使用 Passkey。提交账号验证会使用一次恢复码，即使随后取消设备授权。", "Platform administrators use Passkey. Submitting account verification uses a recovery code once, even if you subsequently cancel device authorization.")}</p></section>`);
      bind("#owner-cli-factor-method", "change", () => {
        const method = root.querySelector("#owner-cli-factor-method")?.value;
        const factor = root.querySelector("#owner-cli-factor");
        if (factor) factor.value = "";
        const label = root.querySelector("#owner-cli-factor-label");
        if (label) label.textContent = method === "backup_code" ? tr("恢复码", "Recovery code") : tr("验证器动态码", "Authenticator code");
      });
      bind("#owner-cli-password-back", "click", () => {
        if (!active() || pending) return;
        clearSecretInputs();
        codePage();
      });
      bind("#owner-cli-password-form", "submit", reviewPassword);
    }

    function clearSecretInputs() {
      for (const selector of ["#owner-cli-account-password", "#owner-cli-factor"]) {
        const input = root.querySelector(selector);
        if (input) input.value = "";
      }
    }

    async function reviewPassword(event) {
      event.preventDefault();
      if (!active() || pending) return;
      const email = String(root.querySelector("#owner-cli-email")?.value || "").trim();
      const password = String(root.querySelector("#owner-cli-account-password")?.value || "");
      const factor = String(root.querySelector("#owner-cli-factor")?.value || "").trim();
      const method = root.querySelector("#owner-cli-factor-method")?.value || "code";
      if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) || email.length > 254 || !password || password.length > 200
        || (method !== "code" && method !== "backup_code") || (factor && (method === "code" ? !/^\d{6}$/.test(factor) : factor.length > 100))) {
        const error = root.querySelector("#owner-cli-error");
        if (error) error.textContent = tr("请填写店铺邮箱与密码；二次验证请使用 6 位动态码或恢复码。", "Enter the shop email and password; use a 6-digit authenticator code or recovery code for second verification.");
        clearSecretInputs();
        return;
      }
      clearSecretInputs();
      const controller = new AbortController();
      pending = controller;
      const version = ++revision;
      const button = root.querySelector("#owner-cli-password-review");
      const back = root.querySelector("#owner-cli-password-back");
      if (button) button.disabled = true;
      if (back) back.disabled = true;
      state = "authenticating";
      try {
        const response = await api("/auth/cli-owner/password-options", { request_id: id, device_code: deviceCode, email, password, ...(factor ? { [method]: factor } : {}) }, "POST", { signal: controller.signal });
        if (!active() || version !== revision) return;
        validate(response, true);
        if (response.mfa_required && !factor) throw new Error("Second verification is required");
        approvalToken = response.approval_token;
        const { approval_token, ...metadata } = response;
        details = metadata;
        approvalMode = "password";
        detailsPage();
      } catch {
        if (active() && version === revision) failed(new Error(tr("账号验证未完成，设备尚未获得授权。请重新核对设备并重试。", "Account verification did not complete. The device has not been authorized. Review the device again and retry.")));
      } finally {
        if (pending === controller) pending = null;
        if (active() && version === revision && button?.isConnected !== false) button.disabled = false;
        if (active() && version === revision && back?.isConnected !== false) back.disabled = false;
      }
    }

    function detailsPage(message = "") {
      if (!details || !active()) return;
      state = "details";
      const password = approvalMode === "password";
      const canPasskey = !!details.options;
      const scope = details.superadmin
        ? `<dt>${tr("授权对象", "Authority")}</dt><dd>${esc(details.shop_name)}</dd><dt>${tr("权限范围", "Permission scope")}</dt><dd><strong>${tr("平台管理员：全部店铺", "Platform administrator: all shops")}</strong><p>${tr("此设备获得平台根管理权限，可管理平台、所有店铺及其商品、卡密、任务、集成与授权记录。", "This device receives platform root administration and can manage the platform, every shop, their products, redemption codes, tasks, integrations and authorization records.")}</p></dd>`
        : `<dt>${tr("授权店铺", "Shop to authorize")}</dt><dd><strong>${esc(details.shop_name)}</strong></dd><dt>${tr("店铺 ID", "Shop ID")}</dt><dd class="mono">${esc(details.shop_id)}</dd><dt>${tr("权限范围", "Permission scope")}</dt><dd><strong>${tr("完整商家管理权限：仅此店铺", "Full merchant management: this shop only")}</strong><p>${tr("此设备可管理上述店铺的商品、卡密、任务队列、集成、授权链接和审计记录。", "This device can manage the named shop's products, redemption codes, task queues, integrations, authorization links and audit records.")}</p></dd>`;
      const action = password || canPasskey
        ? `<button id="owner-cli-approve" type="button">${password ? tr("确认店铺与设备，批准授权", "Confirm shop and device, then approve") : tr("确认设备，使用 Passkey 授权", "Confirm device and authorize with Passkey")}</button>`
        : `<button id="owner-cli-password" type="button">${tr("使用店铺密码验证", "Verify with shop password")}</button>`;
      const alternate = !password && canPasskey && !details.superadmin && details.approval_methods?.some((method) => method === "password" || method === "password_totp")
        ? `<button id="owner-cli-password" class="secondary" type="button">${tr("改用店铺密码验证", "Verify with shop password")}</button>` : "";
      const verification = password ? `<dt>${tr("本次验证方式", "Verification used")}</dt><dd>${details.mfa_required ? tr("新的店铺密码与二次验证", "Fresh shop password and second verification") : tr("新的店铺密码（账号未启用二次验证）", "Fresh shop password (second verification is not enabled)")}</dd>` : "";
      page(`<p>${tr("请与 CLI 显示的设备名、设备码和 SHA-256 指纹逐项核对，并确认授权范围。", "Match the device name, code and SHA-256 fingerprint with your CLI, and confirm the authority scope.")}</p><section class="panel"><h2>${tr("将授权的设备", "Device to authorize")}</h2><dl><dt>${tr("设备名称", "Device name")}</dt><dd>${esc(details.client_name)}</dd><dt>${tr("设备码", "Device code")}</dt><dd class="mono">${esc(details.device_code)}</dd><dt>SHA-256 ${tr("设备指纹", "device fingerprint")}</dt><dd><textarea id="owner-cli-fingerprint" class="mono" rows="2" readonly aria-label="${tr("SHA-256 设备指纹", "SHA-256 device fingerprint")}">${esc(details.fingerprint)}</textarea></dd>${scope}${verification}<dt>${tr("设备授权有效期（30 天）", "Device grant expiry (30 days)")}</dt><dd>${esc(date(details.grant_expires))}</dd><dt>${tr("本次批准请求截止时间", "Approval request expires")}</dt><dd>${esc(date(password ? details.approval_expires : details.expires))}</dd></dl><div class="actions">${action}${alternate}<button id="owner-cli-cancel" class="secondary" type="button">${tr("取消", "Cancel")}</button></div><p id="owner-cli-error" class="error" role="alert">${esc(message)}</p></section>`);
      bind("#owner-cli-approve", "click", approve);
      bind("#owner-cli-password", "click", () => {
        if (!active() || pending) return;
        details = null;
        approvalToken = "";
        passwordPage();
      });
      bind("#owner-cli-cancel", "click", () => {
        if (!active() || pending) return;
        clear();
        state = "cancelled";
        page(`<p>${tr("已取消，设备尚未获得授权。可以关闭此页；CLI 中的请求到期后会自动失效。", "Cancelled. The device has not been authorized. You can close this page; the CLI request will expire automatically.")}</p><button id="owner-cli-again" class="secondary" type="button">${tr("重新核对设备", "Review device again")}</button>`);
        bind("#owner-cli-again", "click", () => codePage());
      });
    }

    async function approve() {
      if (!active() || pending || !details) return;
      const password = approvalMode === "password";
      if ((password ? details.approval_expires : details.expires) * 1000 <= Date.now()) {
        clear();
        state = "expired";
        page(`<p class="error" role="alert">${tr("批准请求已过期，设备尚未获得授权。请在 CLI 中重新发起。", "The approval request has expired. The device has not been authorized. Create a new request in the CLI.")}</p>`);
        return;
      }
      if (!password && (window.isSecureContext === false || typeof window.navigator?.credentials?.get !== "function")) {
        detailsPage(tr("当前浏览器无法使用 Passkey，请在支持 Passkey 的 HTTPS 浏览器中打开此页。", "Passkey is unavailable in this browser. Open this page in a Passkey-capable browser over HTTPS."));
        return;
      }
      const controller = new AbortController();
      pending = controller;
      const version = ++revision;
      const options = details.options;
      const button = root.querySelector("#owner-cli-approve");
      const cancel = root.querySelector("#owner-cli-cancel");
      const alternate = root.querySelector("#owner-cli-password");
      if (button) button.disabled = true;
      if (cancel) cancel.disabled = true;
      if (alternate) alternate.disabled = true;
      state = "authenticating";
      try {
        let response;
        if (password) {
          if (!approvalToken || details.superadmin) throw new Error("Invalid approval");
          const token = approvalToken;
          approvalToken = "";
          response = await api("/auth/cli-owner/password-approve", { request_id: id, device_code: deviceCode, approval_token: token }, "POST", { signal: controller.signal });
        } else {
          const publicKey = { ...options, challenge: decode(options.challenge) };
          if (options.allowCredentials !== undefined)
            publicKey.allowCredentials = options.allowCredentials.map((credential) => ({ ...credential, id: decode(credential.id) }));
          const credential = await window.navigator.credentials.get({ publicKey, signal: controller.signal });
          if (!active() || version !== revision) return;
          if (!credential || credential.type !== "public-key") throw new Error(tr("Passkey 验证未完成，设备尚未获得授权。", "Passkey verification was not completed. The device has not been authorized."));
          response = await api("/auth/cli-owner/verify", {
            request_id: id,
            credential: { id: credential.id, rawId: encode(credential.rawId), type: credential.type,
              response: { clientDataJSON: encode(credential.response.clientDataJSON), authenticatorData: encode(credential.response.authenticatorData), signature: encode(credential.response.signature), userHandle: credential.response.userHandle ? encode(credential.response.userHandle) : null },
              clientExtensionResults: credential.getClientExtensionResults?.() || {} },
          }, "POST", { signal: controller.signal });
        }
        if (!active() || version !== revision) return;
        if (response?.ok !== true || response?.status !== "approved") throw new Error(tr("服务器未确认授权，请检查 CLI 状态。", "The server did not confirm approval. Check the CLI status."));
        if (password && ["role", "scope", "superadmin", "shop_id", "shop_name"].some((key) => response[key] !== details[key]))
          throw new Error(tr("服务器确认的店铺与核对信息不一致。", "The confirmed shop differs from the reviewed details."));
        const name = details.client_name;
        const authority = details.superadmin ? tr("平台管理员：全部店铺", "Platform administrator: all shops") : `${details.shop_name} (${details.shop_id})`;
        clear();
        state = "approved";
        page(`<section class="panel"><h2>${tr("设备已授权", "Device authorized")}</h2><p>${esc(name)}</p><p>${esc(authority)}</p><p>${tr("请回到 CLI 完成登录。此操作仅授权该 CLI 设备，不会更改当前浏览器会话。", "Return to the CLI to finish signing in. Only this CLI device was authorized; the current browser session was not changed.")}</p><a href="/admin">${tr("查看商家后台", "Open merchant dashboard")}</a></section>`);
      } catch (error) {
        if (active() && version === revision) failed(password ? new Error(tr("批准未完成，设备授权状态尚未确认。请检查 CLI 状态并重新核对。", "Approval did not complete and device authorization is unconfirmed. Check the CLI status and review again.")) : error);
      } finally {
        if (pending === controller) pending = null;
        if (active() && version === revision && button?.isConnected !== false) button.disabled = false;
        if (active() && version === revision && cancel?.isConnected !== false) cancel.disabled = false;
        if (active() && version === revision && alternate && alternate.isConnected !== false) alternate.disabled = false;
      }
    }

    const controller = Object.freeze({
      get state() { return state; },
      dispose() {
        if (disposed) return;
        disposed = true;
        revision++;
        pending?.abort();
        pending = null;
        clearSecretInputs();
        clear();
        if (mounts.get(root) === controller) mounts.delete(root);
      },
    });
    mounts.set(root, controller);
    codePage();
    return controller;
  }

  window.ExtoreOwnerCli = Object.freeze({ mount });
})();
