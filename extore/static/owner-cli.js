"use strict";

(() => {
  const mounts = new WeakMap();
  const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
  const esc = (value) => String(value ?? "").replace(/[&<>"']/g, (char) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[char]);
  const codeValue = (value) => String(value ?? "").trim().toUpperCase().replaceAll("-", "");
  const validCode = (value) => /^[ABCDEFGHJKLMNPQRSTUVWXYZ23456789]{12}$/.test(codeValue(value));
  const decode = (value) => {
    if (typeof value !== "string" || !/^[A-Za-z0-9_-]{1,4096}$/.test(value)) throw new Error("Invalid Passkey options");
    return Uint8Array.from(atob(value.replaceAll("-", "+").replaceAll("_", "/")), (char) => char.charCodeAt(0));
  };
  const encode = (value) => btoa(String.fromCharCode(...new Uint8Array(value)))
    .replaceAll("+", "-").replaceAll("/", "_").replace(/=+$/, "");

  function mount({ root, requestId, api, language } = {}) {
    if (!root?.querySelector || typeof api !== "function") throw new TypeError("Owner CLI approval requires a root element and API function");
    mounts.get(root)?.dispose();
    let disposed = false;
    let pending = null;
    let details = null;
    let deviceCode = "";
    let state = "code";
    let revision = 0;
    const id = typeof requestId === "string" ? requestId : "";
    const active = () => !disposed && root.isConnected !== false;
    const lang = () => {
      const preferred = typeof language === "function" ? language() : language;
      return String(preferred || window.ExtorePreferences?.resolved?.language || window.navigator?.language || "zh-CN").toLowerCase().startsWith("en") ? "en" : "zh-CN";
    };
    const tr = (cn, en) => lang() === "en" ? en : cn;
    const date = (seconds) => new Date(seconds * 1000).toLocaleString(lang() === "en" ? "en-GB" : "zh-CN");
    const page = (body) => {
      if (active()) root.innerHTML = `<div class="narrow"><h1>${tr("授权商家 CLI 设备", "Authorize merchant CLI device")}</h1>${body}</div>`;
    };
    const errorText = (error) => {
      if (error?.name === "NotAllowedError" || error?.name === "AbortError")
        return tr("Passkey 验证已取消或超时，设备尚未获得授权。确认 CLI 仍在等待后可以重试。", "Passkey verification was cancelled or timed out. The device has not been authorized. You can retry while the CLI request is still pending.");
      return typeof error?.message === "string" && error.message.length <= 1000
        ? error.message
        : tr("授权未完成，请检查 CLI 请求后重试。", "Authorization was not completed. Check the CLI request and retry.");
    };
    const bind = (selector, event, handler) => root.querySelector(selector)?.addEventListener(event, handler);
    const clear = () => { details = null; deviceCode = ""; };
    function failed(error) {
      const message = errorText(error);
      details = null;
      codePage(message);
      if (/过期|失效|expired/i.test(message)) state = "expired";
      else if (/拒绝|撤销|denied|revoked/i.test(message)) state = "denied";
      else if (error?.name === "NotAllowedError" || error?.name === "AbortError") state = "cancelled";
      else state = "error";
    }

    function codePage(message = "") {
      state = uuid.test(id) ? "code" : "invalid";
      if (state === "invalid") {
        page(`<p class="error" role="alert">${tr("授权请求 ID 无效，请使用 CLI 刚生成的完整授权网址。", "Invalid authorization request ID. Open the complete authorization URL generated by the CLI.")}</p><a href="/">${tr("返回首页", "Return home")}</a>`);
        return;
      }
      page(`<p>${tr("在 CLI 中核对正在等待授权的设备，再输入它显示的设备码。", "Check the device waiting for authorization in your CLI, then enter the device code it displays.")}</p><section class="panel"><form id="owner-cli-code-form"><div class="field"><label for="owner-cli-code">${tr("CLI 设备码", "CLI device code")}</label><input id="owner-cli-code" class="code" autocomplete="off" autocapitalize="characters" spellcheck="false" maxlength="64" required placeholder="XXXX-XXXX-XXXX" value="${esc(deviceCode)}"></div><button id="owner-cli-review" type="submit">${tr("核对设备与权限", "Review device and permissions")}</button></form><p id="owner-cli-error" class="error" role="alert">${esc(message)}</p></section><p class="caption">${tr("核对设备不会授权。下一步确认设备指纹与商家权限后，才会请求 Passkey。", "Reviewing does not authorize the device. Passkey verification is requested only after you explicitly approve the device fingerprint and merchant permissions.")}</p>`);
      bind("#owner-cli-code-form", "submit", async (event) => {
        event.preventDefault();
        if (!active() || pending) return;
        const input = root.querySelector("#owner-cli-code");
        deviceCode = String(input?.value || "").trim().toUpperCase();
        if (!validCode(deviceCode)) {
          const error = root.querySelector("#owner-cli-error");
          if (error) error.textContent = tr("请输入 CLI 显示的 12 位设备码，例如 XXXX-XXXX-XXXX。", "Enter the 12-character device code displayed by the CLI, such as XXXX-XXXX-XXXX.");
          input?.focus();
          return;
        }
        const button = root.querySelector("#owner-cli-review");
        if (button) button.disabled = true;
        const controller = new AbortController();
        pending = controller;
        const version = ++revision;
        try {
          const response = await api("/auth/cli-owner/options", { request_id: id, device_code: deviceCode }, "POST", { signal: controller.signal });
          if (!active() || version !== revision) return;
          validate(response);
          details = response;
          detailsPage();
        } catch (error) {
          if (active() && version === revision) failed(error);
        } finally {
          if (pending === controller) pending = null;
          if (active() && version === revision && button?.isConnected !== false) button.disabled = false;
        }
      });
    }

    function validate(value) {
      const options = value?.options;
      const hostname = new URL(window.location.origin).hostname;
      if (!value || typeof value.request_id !== "string" || value.request_id.toLowerCase() !== id.toLowerCase()
        || value.role !== "admin" || value.scope !== "shop.owner" || !validCode(value.device_code)
        || codeValue(value.device_code) !== codeValue(deviceCode)
        || typeof value.client_name !== "string" || value.client_name.length > 200
        || !/^[0-9a-f]{64}$/.test(value.fingerprint || "")
        || !Number.isFinite(value.expires) || value.expires * 1000 <= Date.now()
        || value.expires * 1000 > Date.now() + 630 * 1000
        || !Number.isFinite(value.grant_expires) || value.grant_expires * 1000 <= Date.now()
        || value.grant_expires * 1000 > Date.now() + (30 * 86400 + 300) * 1000
        || !options || options.userVerification !== "required" || options.rpId !== hostname
        || (options.allowCredentials !== undefined && (!Array.isArray(options.allowCredentials) || options.allowCredentials.length > 128)))
        throw new Error(tr("设备授权信息无效或已过期，请从 CLI 重新申请。", "Device authorization details are invalid or expired. Create a new request in the CLI."));
      decode(options.challenge);
      options.allowCredentials?.forEach((credential) => {
        if (credential?.type !== "public-key") throw new Error(tr("Passkey 验证信息无效。", "Invalid Passkey verification options."));
        decode(credential.id);
      });
    }

    function detailsPage(message = "") {
      if (!details || !active()) return;
      state = "details";
      page(`<p>${tr("请与 CLI 显示的设备名、设备码和 SHA-256 指纹逐项核对。", "Match the device name, code and SHA-256 fingerprint with those displayed in the CLI.")}</p><section class="panel"><h2>${tr("将授权的设备", "Device to authorize")}</h2><dl><dt>${tr("设备名称", "Device name")}</dt><dd>${esc(details.client_name)}</dd><dt>${tr("设备码", "Device code")}</dt><dd class="mono">${esc(details.device_code)}</dd><dt>SHA-256 ${tr("设备指纹", "device fingerprint")}</dt><dd><textarea id="owner-cli-fingerprint" class="mono" rows="2" readonly aria-label="${tr("SHA-256 设备指纹", "SHA-256 device fingerprint")}">${esc(details.fingerprint)}</textarea></dd><dt>${tr("权限范围", "Permission scope")}</dt><dd><strong>${tr("完整商家管理权限", "Full merchant management")}</strong><p>${tr("此设备可管理整个商店的商品、卡密、任务队列、集成、授权链接和审计记录。", "This device can manage the entire shop, including products, redemption codes, task queues, integrations, authorization links and audit records.")}</p></dd><dt>${tr("设备授权有效期（30 天）", "Device grant expiry (30 days)")}</dt><dd>${esc(date(details.grant_expires))}</dd><dt>${tr("本次批准请求截止时间", "Approval request expires")}</dt><dd>${esc(date(details.expires))}</dd></dl><div class="actions"><button id="owner-cli-approve" type="button">${tr("确认设备，使用 Passkey 授权", "Confirm device and authorize with Passkey")}</button><button id="owner-cli-cancel" class="secondary" type="button">${tr("取消", "Cancel")}</button></div><p id="owner-cli-error" class="error" role="alert">${esc(message)}</p></section>`);
      bind("#owner-cli-approve", "click", approve);
      bind("#owner-cli-cancel", "click", () => {
        if (!active() || pending) return;
        clear();
        state = "cancelled";
        page(`<p>${tr("已取消，设备尚未获得授权。可以关闭此页；CLI 中的请求到期后会自动失效。", "Cancelled. The device has not been authorized. You can close this page; the CLI request will expire automatically.")}</p><button id="owner-cli-again" class="secondary" type="button">${tr("重新核对设备", "Review device again")}</button>`);
        bind("#owner-cli-again", "click", () => codePage());
      });
    }

    async function approve() {
      if (!active() || pending || !details) return;
      if (details.expires * 1000 <= Date.now()) {
        clear();
        state = "expired";
        page(`<p class="error" role="alert">${tr("批准请求已过期，设备尚未获得授权。请在 CLI 中重新发起。", "The approval request has expired. The device has not been authorized. Create a new request in the CLI.")}</p>`);
        return;
      }
      if (window.isSecureContext === false || typeof window.navigator?.credentials?.get !== "function") {
        detailsPage(tr("当前浏览器无法使用 Passkey，请在支持 Passkey 的 HTTPS 浏览器中打开此页。", "Passkey is unavailable in this browser. Open this page in a Passkey-capable browser over HTTPS."));
        return;
      }
      const controller = new AbortController();
      pending = controller;
      const version = ++revision;
      const options = details.options;
      const button = root.querySelector("#owner-cli-approve");
      const cancel = root.querySelector("#owner-cli-cancel");
      if (button) button.disabled = true;
      if (cancel) cancel.disabled = true;
      state = "authenticating";
      try {
        const publicKey = { ...options, challenge: decode(options.challenge) };
        if (options.allowCredentials !== undefined)
          publicKey.allowCredentials = options.allowCredentials.map((credential) => ({ ...credential, id: decode(credential.id) }));
        const credential = await window.navigator.credentials.get({ publicKey, signal: controller.signal });
        if (!active() || version !== revision) return;
        if (!credential || credential.type !== "public-key") throw new Error(tr("Passkey 验证未完成，设备尚未获得授权。", "Passkey verification was not completed. The device has not been authorized."));
        const response = await api("/auth/cli-owner/verify", {
          request_id: id,
          credential: { id: credential.id, rawId: encode(credential.rawId), type: credential.type,
            response: { clientDataJSON: encode(credential.response.clientDataJSON), authenticatorData: encode(credential.response.authenticatorData), signature: encode(credential.response.signature), userHandle: credential.response.userHandle ? encode(credential.response.userHandle) : null },
            clientExtensionResults: credential.getClientExtensionResults?.() || {} },
        }, "POST", { signal: controller.signal });
        if (!active() || version !== revision) return;
        if (response?.ok !== true || response?.status !== "approved") throw new Error(tr("服务器未确认授权，请检查 CLI 状态。", "The server did not confirm approval. Check the CLI status."));
        const name = details.client_name;
        clear();
        state = "approved";
        page(`<section class="panel"><h2>${tr("设备已授权", "Device authorized")}</h2><p>${esc(name)}</p><p>${tr("请回到 CLI 完成登录。此操作仅授权该 CLI 设备，不会更改当前浏览器会话。", "Return to the CLI to finish signing in. Only this CLI device was authorized; the current browser session was not changed.")}</p><a href="/admin">${tr("查看商家后台", "Open merchant dashboard")}</a></section>`);
      } catch (error) {
        if (active() && version === revision) failed(error);
      } finally {
        if (pending === controller) pending = null;
        if (active() && version === revision && button?.isConnected !== false) button.disabled = false;
        if (active() && version === revision && cancel?.isConnected !== false) cancel.disabled = false;
      }
    }

    const controller = Object.freeze({
      get state() { return state; },
      dispose() {
        if (disposed) return;
        disposed = true;
        revision++;
        pending?.abort();
        pending = null;
        clear();
        if (mounts.get(root) === controller) mounts.delete(root);
      },
    });
    mounts.set(root, controller);
    codePage();
    return controller;
  }

  window.ExtoreOwnerCli = Object.freeze({ mount });
})();
